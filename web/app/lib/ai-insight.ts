const BY_MODULE: Record<string, Insight> = {
  政治理论: {
    thoughts: ["牢记重大会议表述与关键词对应关系", "抓核心词：新思想、中国式现代化、全过程人民民主"],
    pitfalls: ["把不同会议的表述串位", "对“首次提出”“根本要求”等提法记混"],
  },
};

export function getInsight(module?: string | null, qtype?: string | null): Insight {
  if (qtype && BY_QTYPE[qtype]) return BY_QTYPE[qtype];
  if (module && BY_MODULE[module]) return BY_MODULE[module];
  // 按模块粗分兜底
  if (module === "判断推理") return BY_QTYPE["逻辑判断"];
  if (module === "言语理解与表达") return BY_QTYPE["言语理解与表达"];
  return {
    thoughts: ["先明确题目问什么，再定位材料/选项中的对应信息", "排除法与直选结合，优先排除绝对化与无关项"],
    pitfalls: ["审题不清导致答非所问", "未核对单位与限定条件"],
  };
}
